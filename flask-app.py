# Imports & app setup
from flask import Flask, request, jsonify
# Flask     -> the class used to create the web application instance
# request   -> gives access to incoming HTTP request data (JSON body, headers, etc.)
# jsonify   -> converts Python dicts/lists into a proper JSON HTTP response

app = Flask(__name__)
# Creates the Flask application object.
# __name__ tells Flask the current module's name, used internally to locate
# resources (templates, static files) relative to this file.
"""
Real-world difference: In production, app = Flask(__name__) is usually 
created inside an app factory function (create_app()), 
not at module level — this makes it possible to spin up multiple app instances 
(e.g., one for tests, one for production) with different configs.
"""

# In-memory "database"
items = {}
# A plain Python dict acting as a fake database.
# Key = item id, Value = the item's data.

next_id = 1
# Tracks the next available id to assign to a newly created item.
"""
Real-world difference: This is replaced entirely by a real database 
(PostgreSQL/MySQL/SQLite) accessed through an ORM like SQLAlchemy. 
IDs are auto-generated by the database, not tracked manually — and 
data survives server restarts, which this dict does not.
"""
# Health check route
@app.route("/", methods=["GET"])
# Decorator: binds the function below to the URL path "/" for GET requests.
def health_check():
    return jsonify({"status": "ok", "message": "Flask CRUD API is running"}), 200
    # jsonify(...) builds the JSON response body.
    # The second value, 200, is the HTTP status code (OK).
'''
Real-world difference: Production health checks often also verify the 
database connection is alive (e.g., run a trivial query) 
so load balancers/orchestrators (Kubernetes, AWS ELB) know if the app 
is actually healthy, not just "the process is running."
'''
# GET all items
@app.route("/items", methods=["GET"])
def get_items():
    return jsonify(list(items.values())), 200
    # items.values() -> all the item dicts in our store
    # list(...)       -> converts the dict_values view into a list
    # jsonify(...)    -> serializes that list into a JSON array response
'''
Real-world difference: Real APIs almost never return all rows unpaginated 
— you'd add ?page=1&limit=20 query params and return a subset, 
plus filtering/sorting (?sort=name&order=asc).
'''
# GET single item
@app.route("/items/<int:item_id>", methods=["GET"])
# <int:item_id> is a URL converter: it extracts the id from the path AND
# automatically casts it to an int (so item_id arrives as 3, not "3").
def get_item(item_id):
    item = items.get(item_id)
    # dict.get() returns None if the key doesn't exist, instead of raising KeyError.
    if not item:
        return jsonify({"error": "Item not found"}), 404
        # 404 = Not Found, the standard REST status code for a missing resource.
    return jsonify(item), 200
'''
Real-world difference: items.get(item_id) becomes 
Item.query.get(item_id) (SQLAlchemy) — same idea, 
but querying an actual table instead of a Python dict.
'''
# POST — create item
@app.route("/items", methods=["POST"])
def create_item():
    global next_id
    # Required because we're reassigning next_id (a module-level variable)
    # inside this function — without `global`, Python would treat it as a
    # new local variable and throw an UnboundLocalError on next_id += 1.

    data = request.get_json(silent=True)
    # Parses the incoming JSON request body into a Python dict.
    # silent=True -> returns None instead of raising an error if parsing fails
    # (e.g., missing Content-Type header, or malformed JSON).

    if not data or "name" not in data:
        return jsonify({"error": "'name' field is required"}), 400
        # 400 = Bad Request, since the client sent an invalid/incomplete payload.

    new_item = {
        "id": next_id,
        "name": data["name"],
        "description": data.get("description", ""),
        # .get() with a default avoids a KeyError if "description" is omitted.
    }
    items[next_id] = new_item   # save the item into our fake database
    next_id += 1                 # bump the counter for the next item

    return jsonify(new_item), 201
    # 201 = Created — the correct status code for a successful POST that
    # creates a new resource (not 200).
'''
Real-world difference: global next_id disappears entirely — the database 
generates the ID. Validation ("name" not in data) is usually handled by a 
schema library (Pydantic, Marshmallow) that also checks types, lengths, 
formats — not just presence.
'''
# PUT — update item
@app.route("/items/<int:item_id>", methods=["PUT"])
def update_item(item_id):
    item = items.get(item_id)
    if not item:
        return jsonify({"error": "Item not found"}), 404

    data = request.get_json(silent=True)
    if not data:
        return jsonify({"error": "Request body must be JSON"}), 400

    item["name"] = data.get("name", item["name"])
    # If "name" is in the request body, use it; otherwise keep the existing value.
    item["description"] = data.get("description", item["description"])

    return jsonify(item), 200
    # 200 = OK, standard for a successful update.
'''
Real-world difference: Real projects distinguish PUT 
(full replace — client must send all fields) from PATCH 
(partial update — this code's actual behavior). This code is 
technically doing a PATCH under a PUT route. Also, updates go 
through db.session.commit() instead of mutating a dict in place.
'''
# DELETE item
@app.route("/items/<int:item_id>", methods=["DELETE"])
def delete_item(item_id):
    item = items.pop(item_id, None)
    # dict.pop(key, default) removes the key and returns its value,
    # or returns None (instead of raising KeyError) if the key isn't found.
    if not item:
        return jsonify({"error": "Item not found"}), 404

    return jsonify({"message": f"Item {item_id} deleted", "item": item}), 200
'''
Real-world difference: Many real APIs use soft deletes 
(mark a row is_deleted = True instead of actually removing it) 
to preserve audit history and allow recovery. Hard deletes like 
this are more common only for genuinely disposable data.
'''
# Entry point
if __name__ == "__main__":
    app.run(debug=True, port=5000)
    # Only runs the built-in dev server if this file is executed directly
    # (not when imported as a module elsewhere).
    # debug=True enables auto-reload + detailed error pages — dev only.